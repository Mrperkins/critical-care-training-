/**
 * Writes src/library/lessonMinutes.ts: the real length of every lesson a module lists, as the player itself
 * reports it (narration + checkpoints + self-check). Run after editing lesson scripts: `npx tsx scripts/gen-lesson-minutes.ts`.
 * tests/lesson-minutes.test.ts fails when the table is stale.
 */
import fs from 'node:fs';
import path from 'node:path';
const g = globalThis as Record<string, unknown>;
g.window ??= g; g.matchMedia ??= () => ({ matches: false, addEventListener() {}, removeEventListener() {} });
g.document ??= { addEventListener() {}, createElement: () => ({ getContext: () => null, style: {} }), documentElement: { style: {} }, querySelector: () => null, hidden: false };
g.navigator ??= { userAgent: '' }; g.requestAnimationFrame ??= () => 0;
(async () => {
  const { computeLessonMinutes } = await import('../src/library/lessonMinutesCompute');
  const table = await computeLessonMinutes();
  const body = `/** GENERATED by scripts/gen-lesson-minutes.ts — the length the player reports for each module lesson. Do not edit by hand. */\nexport const LESSON_MINUTES: Record<string, number> = ${JSON.stringify(table, null, 2)};\n`;
  fs.writeFileSync(path.resolve('src/library/lessonMinutes.ts'), body);
  console.log('lessons', Object.keys(table).length, 'total min', Object.values(table).reduce((a, b) => a + b, 0));
})();
